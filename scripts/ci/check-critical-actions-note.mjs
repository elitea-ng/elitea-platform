#!/usr/bin/env node
// The critical-actions upgrade note guard of ADR-0059 R1.2b (#2592).
//
// From R1.2b a personal access token with administration access is refused
// on every `critical` action of the action table whose entry says
// `token: never`. That refusal is the one change that can break existing
// automation on the day of the upgrade, so the upgrade note lists every
// critical (route, action) entry, generated from the registry.
//
// The chain from the registry to the note has two links, each held by CI:
//
//   * services/elitea-main/internal/adminaccess/testdata/actions.golden is
//     the action table, one line per entry. TestActionTableMatchesGolden
//     fails when the table and the golden disagree.
//   * this script fails when the note's generated block does not list every
//     critical entry of the golden, exactly, with its token rule.
//
//   node scripts/ci/check-critical-actions-note.mjs           # check
//   node scripts/ci/check-critical-actions-note.mjs --write   # regenerate

import fs from 'node:fs';
import path from 'node:path';
import process from 'node:process';
import { fileURLToPath } from 'node:url';

export const GOLDEN = 'services/elitea-main/internal/adminaccess/testdata/actions.golden';
export const NOTE = 'docs/upgrading/2026-11-24-2506-tokens-refused-on-critical-actions.md';
export const BEGIN = '<!-- critical-actions:begin (generated by scripts/ci/check-critical-actions-note.mjs --write) -->';
export const END = '<!-- critical-actions:end -->';

// criticalEntries reads the golden: method, route, action, danger, reason,
// elevation, token, tab-separated; `#` lines are comments.
export function criticalEntries(golden) {
  const entries = [];
  for (const line of golden.split('\n')) {
    if (line === '' || line.startsWith('#')) continue;
    const fields = line.split('\t');
    if (fields.length !== 7) throw new Error(`${GOLDEN}: malformed line ${JSON.stringify(line)}`);
    const [method, route, action, danger, , , token] = fields;
    if (danger === 'critical') entries.push({ method, route, action, token });
  }
  return entries;
}

// renderBlock is the generated table of the note.
export function renderBlock(entries) {
  const rows = entries.map(({ method, route, action, token }) => {
    const rule = token === 'never'
      ? 'refused'
      : 'inherit token of a standing global administrator only';
    return `| \`${method}\` | \`${route}\` | ${action === '-' ? '' : `\`${action}\``} | ${rule} |`;
  });
  return [
    BEGIN,
    '| Method | Route | Action | A `scoped` or `inherit` token |',
    '|---|---|---|---|',
    ...rows,
    END,
  ].join('\n');
}

// check answers the problems of note against golden, [] when it is current.
export function check(note, golden) {
  const begin = note.indexOf(BEGIN);
  const end = note.indexOf(END);
  if (begin < 0 || end < begin) {
    return [`${NOTE} has no generated block between "${BEGIN}" and "${END}"`];
  }
  const want = renderBlock(criticalEntries(golden));
  const got = note.slice(begin, end + END.length);
  if (got === want) return [];
  const wantRows = new Set(want.split('\n'));
  const gotRows = new Set(got.split('\n'));
  const problems = [];
  for (const row of wantRows) if (!gotRows.has(row)) problems.push(`missing: ${row}`);
  for (const row of gotRows) if (!wantRows.has(row)) problems.push(`not in the registry: ${row}`);
  if (problems.length === 0) problems.push('the rows are out of order');
  return [
    `${NOTE} does not list the critical actions of the registry; regenerate it with ` +
      '`node scripts/ci/check-critical-actions-note.mjs --write`',
    ...problems,
  ];
}

// write regenerates the block of note from golden.
export function write(note, golden) {
  const begin = note.indexOf(BEGIN);
  const end = note.indexOf(END);
  if (begin < 0 || end < begin) throw new Error(`${NOTE} has no generated block to regenerate`);
  return note.slice(0, begin) + renderBlock(criticalEntries(golden)) + note.slice(end + END.length);
}

function main(argv) {
  const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
  const golden = fs.readFileSync(path.join(root, GOLDEN), 'utf8');
  const notePath = path.join(root, NOTE);
  const note = fs.readFileSync(notePath, 'utf8');
  if (argv.includes('--write')) {
    fs.writeFileSync(notePath, write(note, golden));
    return 0;
  }
  const problems = check(note, golden);
  for (const problem of problems) console.error(`::error::${problem}`);
  if (problems.length === 0) console.log(`critical actions note: ${criticalEntries(golden).length} entries, current`);
  return problems.length === 0 ? 0 : 1;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  process.exit(main(process.argv.slice(2)));
}
