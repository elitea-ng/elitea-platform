#!/usr/bin/env node
/**
 * The blueprint gallery's data for the app (issue 3137). The repo-root
 * `scripts/blueprints/build.mjs` turns `blueprints/` into the index that the
 * web gallery, the docs and the release assets use. The app ships the part of
 * that index it shows (names, descriptions, briefs, what each one shows and
 * needs), so the gallery works offline and matches the build it came with.
 *
 *   node scripts/blueprints.mjs          write src/features/blueprints/blueprints.gen.ts
 *   node scripts/blueprints.mjs --check  exit 1 when the committed file is stale
 *
 * The app does not import blueprint files (that is a follow-up issue), so the
 * file names and avatars stay out.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import process from 'node:process';
import { fileURLToPath } from 'node:url';

import { parse, stringify } from 'yaml';

import { buildBlueprints } from '../../../scripts/blueprints/build.mjs';

const APP_ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const REPO_ROOT = resolve(APP_ROOT, '../..');
export const GENERATED = resolve(APP_ROOT, 'src/features/blueprints/blueprints.gen.ts');

function entry(item) {
  return {
    slug: item.slug,
    name: item.name,
    description: item.description,
    brief: item.brief,
    showcases: item.showcases,
    requirements: item.requirements.map((requirement) => requirement.label),
    surface: item.surface,
  };
}

/** The app's gallery data, as the TypeScript module that is committed. */
export async function appBlueprints(root = REPO_ROOT) {
  const { index } = await buildBlueprints({ root, parseYaml: (text) => parse(text), dumpYaml: (value) => stringify(value) });
  const data = {
    agents: index.agents.map(entry),
    teams: index.teams.map((team) => ({ ...entry(team), members: team.members.map((member) => member.name) })),
  };
  return [
    '// Generated by scripts/blueprints.mjs from blueprints/ (issue 3137). Do not edit.',
    "import type { BlueprintData } from './types';",
    '',
    `export const BLUEPRINT_DATA: BlueprintData = ${JSON.stringify(data, null, 2)};`,
    '',
  ].join('\n');
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const text = await appBlueprints();
  if (process.argv.includes('--check')) {
    if (readFileSync(GENERATED, 'utf8') !== text) {
      console.error('src/features/blueprints/blueprints.gen.ts is stale: run node scripts/blueprints.mjs');
      process.exit(1);
    }
  } else {
    writeFileSync(GENERATED, text);
  }
}
