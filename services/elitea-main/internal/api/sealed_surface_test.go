package api_test

// The sealed session is honoured on the administration surface only (ADR-0059
// R2.7a, issue 2521). The binary reads the surface from
// internal/adminaccess/administration_surface.txt (adminaccess.
// OnAdministrationSurface); this file keeps that list equal to what the
// driver finds in the composed router, and proves the request-time lookup
// apimw.Auth uses (chi's Find on the root router) lands every surface route
// on its own pattern.

import (
	"net/http"
	"os"
	"path/filepath"
	"slices"
	"strings"
	"testing"

	"github.com/go-chi/chi/v5"

	"github.com/elitea-ng/elitea-platform/services/elitea-main/internal/adminaccess"
	"github.com/elitea-ng/elitea-platform/services/elitea-main/internal/api/adminsurface"
	"github.com/elitea-ng/elitea-platform/services/elitea-main/internal/auth"
)

var sealedSurfaceFile = filepath.Join("..", "adminaccess", "administration_surface.txt")

const sealedSurfaceHeader = "# Generated by TestSealedSurfaceMatchesTheDrivenSurface (internal/api); UPDATE_GOLDEN=1 rewrites it.\n"

func drivenSurfaceRoutes(t *testing.T) []string {
	t.Helper()
	driven := drivenComposedSurface(t)
	var routes []string
	for _, entry := range driven.result.Surface {
		switch entry.Variant {
		case adminsurface.VariantNativeSession, adminsurface.VariantMaintenance, adminsurface.VariantModeration:
			// Reached only by a native device session, during a maintenance
			// window (the bypass check of a user route) or through the
			// Marketplace's default-mode gate: none is an administration
			// route a sealed session needs, so a route reached ONLY this way
			// stays off its surface.
			continue
		}
		routes = append(routes, entry.Method+" "+adminaccess.RoutePattern(entry.Pattern))
	}
	slices.Sort(routes)
	return slices.Compact(routes)
}

func TestSealedSurfaceMatchesTheDrivenSurface(t *testing.T) {
	want := drivenSurfaceRoutes(t)
	if len(want) < 100 {
		t.Fatalf("the driven surface has %d routes; the composed router has far more", len(want))
	}
	if os.Getenv("UPDATE_GOLDEN") == "1" {
		if err := os.WriteFile(sealedSurfaceFile, []byte(sealedSurfaceHeader+strings.Join(want, "\n")+"\n"), 0o644); err != nil {
			t.Fatal(err)
		}
		t.Skip("regenerated; rerun without UPDATE_GOLDEN to compare against the embedded copy")
	}
	got := adminaccess.AdministrationSurface()
	for _, route := range want {
		if !slices.Contains(got, route) {
			t.Errorf("%s is on the administration surface but not in %s: the sealed session would be refused there "+
				"(regenerate with UPDATE_GOLDEN=1)", route, sealedSurfaceFile)
		}
	}
	for _, route := range got {
		if !slices.Contains(want, route) {
			t.Errorf("%s is in %s but not on the administration surface: the sealed session would reach it "+
				"(regenerate with UPDATE_GOLDEN=1)", route, sealedSurfaceFile)
		}
	}
}

// The middleware finds the route of a request with chi's Find on the root
// router before the route runs. Every surface route must be found as itself
// on the path the driver requests, and a `{mode}` route only in the
// administration mode.
func TestSealedSurfaceIsFoundAtRequestTime(t *testing.T) {
	composed, err := adminsurface.ComposedRouter()
	if err != nil {
		t.Fatal(err)
	}
	routes, ok := composed.Handler.(chi.Routes)
	if !ok {
		t.Fatalf("the composed handler %T is not a chi router: apimw.Auth could not find its routes", composed.Handler)
	}
	lookup := func(method, path string) bool {
		rctx := chi.NewRouteContext()
		return adminaccess.OnAdministrationSurface(method, routes.Find(rctx, method, path), rctx.URLParam)
	}
	moded := 0
	for _, route := range adminaccess.AdministrationSurface() {
		method, pattern, _ := strings.Cut(route, " ")
		path := adminsurface.RequestPath(pattern, nil)
		if !lookup(method, path) {
			t.Errorf("%s: %s %s is not found on the surface at request time", route, method, path)
		}
		if strings.Contains(pattern, "{mode}") {
			moded++
			for _, mode := range []string{auth.PermissionModeDefault, auth.PermissionModeDeveloper} {
				other := adminsurface.RequestPath(pattern, map[string]string{"mode": mode})
				if lookup(method, other) {
					t.Errorf("%s: %s %s (mode %s) is treated as the administration surface", route, method, other, mode)
				}
			}
		}
	}
	if moded == 0 {
		t.Error("no {mode} route on the surface: the mode check above checked nothing")
	}
	// Routes every browser reaches that are not administration.
	for _, probe := range []struct{ method, path string }{
		{http.MethodGet, "/api/v2/elitea_core/applications/prompt_lib/1"},
		{http.MethodPost, "/api/v2/auth/token"},
		{http.MethodGet, "/api/v2/elitea_core/platform_settings/prompt_lib"},
		{http.MethodGet, "/healthz"},
	} {
		if lookup(probe.method, probe.path) {
			t.Errorf("%s %s is treated as the administration surface", probe.method, probe.path)
		}
	}
}
