func TestLocalValidatorPreservesDatabaseFailures(t *testing.T) {
	const secret = "0123456789abcdef0123456789abcdef0123456789abcdef0123456789abcdef"
	token := jwt.NewWithClaims(jwt.SigningMethodHS512, tokenClaims{UUID: "8ce4be49-0d10-4f05-a63f-d6d46f99a3f0"})
	encoded, err := token.SignedString([]byte(secret))
	if err != nil {
		t.Fatal(err)
	}
	want := errors.New("database unavailable")
	validator := &LocalValidator{
		secretKey: []byte(secret),
		queries: activePATQueriesFunc(func(context.Context, string) (sqlcgen.GetActivePATPrincipalByUUIDRow, error) {
			return sqlcgen.GetActivePATPrincipalByUUIDRow{}, want
		}),
	}

	_, err = validator.ValidateToken(context.Background(), encoded)
	if !errors.Is(err, ErrTokenValidationUnavailable) || !errors.Is(err, want) {
		t.Fatalf("error = %v, want unavailable plus wrapped database failure", err)
	}
}
