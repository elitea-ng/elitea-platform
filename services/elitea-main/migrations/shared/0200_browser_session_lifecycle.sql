-- 0200_browser_session_lifecycle.sql — session records (ADR-0042 decision 5,
-- issue #1496).
--
-- A browser session row (0117) gains what its audit events need:
--
--   ref               a stable, NON-SECRET reference of the session. The row
--                     id is the cookie value and therefore the credential;
--                     it never leaves this table. `ref` is a server-assigned
--                     bigint with no relation to the id, so knowing it grants
--                     nothing. Audit events name a session by `ref`
--                     (entity_type browser_session, entity_id ref), and a run
--                     a browser request started records the same value
--                     (execution_jobs.browser_session_ref, shared 0201), so
--                     the two join.
--   ended_at          when the session stopped authenticating anybody: the
--   end_reason        deadline it passed (idle, absolute) or the moment it
--                     was signed out (logout) or revoked by an operator or a
--                     deactivation (revoked). The FIRST end wins and is never
--                     rewritten. Expiry is stamped when a request meets the
--                     expired row or when the sweep finds it, whichever is
--                     first; ended_at is then the deadline itself, not the
--                     time it was noticed.
--   start_audited_at  the audit relay's marks. A lifecycle change is a row
--   end_audited_at    change in the SAME statement that makes it, and the
--                     relay (main.browser_session_audit) writes the event to
--                     centry.audit_events and stamps the mark in one
--                     transaction. So an event is written exactly once, and
--                     a revocation inside a caller's transaction
--                     (nativeauth.RevokeUserSessions) produces its event only
--                     if that transaction commits.
--
-- EXISTING ROWS. Their start is marked audited at created_at: they started
-- before the event existed, and a burst of back-dated starts on upgrade would
-- be noise. A row already revoked is marked ended (revoked) and audited for
-- the same reason. Live rows produce their end event when they end.
--
-- Additive only. Idempotent. No BEGIN/COMMIT: the ledgered runner wraps the
-- file. Adding the identity column fills it for every existing row; the
-- table holds one row per browser sign-in, so the rewrite is small.

ALTER TABLE elitea_auth.browser_sessions
    ADD COLUMN IF NOT EXISTS ref bigint GENERATED BY DEFAULT AS IDENTITY;

CREATE UNIQUE INDEX IF NOT EXISTS browser_sessions_ref_key
    ON elitea_auth.browser_sessions (ref);

ALTER TABLE elitea_auth.browser_sessions
    ADD COLUMN IF NOT EXISTS ended_at timestamptz,
    ADD COLUMN IF NOT EXISTS end_reason text,
    ADD COLUMN IF NOT EXISTS start_audited_at timestamptz,
    ADD COLUMN IF NOT EXISTS end_audited_at timestamptz;

DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
        WHERE conname = 'browser_sessions_end_reason_known'
          AND conrelid = 'elitea_auth.browser_sessions'::regclass
    ) THEN
        ALTER TABLE elitea_auth.browser_sessions
            ADD CONSTRAINT browser_sessions_end_reason_known CHECK (
                (ended_at IS NULL AND end_reason IS NULL)
                OR (ended_at IS NOT NULL
                    AND end_reason IN ('idle', 'absolute', 'logout', 'revoked'))
            );
    END IF;
END
$$;

UPDATE elitea_auth.browser_sessions
SET start_audited_at = created_at
WHERE start_audited_at IS NULL;

UPDATE elitea_auth.browser_sessions
SET ended_at = revoked_at, end_reason = 'revoked', end_audited_at = revoked_at
WHERE revoked_at IS NOT NULL AND ended_at IS NULL;

-- Sessions that had already lapsed before this migration end here, quietly:
-- their expiry happened before session events existed, and reporting it now
-- would send one burst of stale `session.expire` events on the first pass.
-- The idle deadline is taken when it falls before the absolute one.
UPDATE elitea_auth.browser_sessions
SET ended_at = last_seen_at + make_interval(secs => idle_timeout_seconds),
    end_reason = 'idle',
    end_audited_at = now()
WHERE ended_at IS NULL
  AND revoked_at IS NULL
  AND idle_timeout_seconds > 0
  AND last_seen_at + make_interval(secs => idle_timeout_seconds) <= LEAST(now(), expires_at);

UPDATE elitea_auth.browser_sessions
SET ended_at = expires_at, end_reason = 'absolute', end_audited_at = now()
WHERE ended_at IS NULL
  AND revoked_at IS NULL
  AND expires_at <= now();

-- The relay's two queues. Both stay small: a row leaves each the moment its
-- event is written.
CREATE INDEX IF NOT EXISTS browser_sessions_start_unaudited
    ON elitea_auth.browser_sessions (created_at)
    WHERE start_audited_at IS NULL;

CREATE INDEX IF NOT EXISTS browser_sessions_end_unaudited
    ON elitea_auth.browser_sessions (ended_at)
    WHERE ended_at IS NOT NULL AND end_audited_at IS NULL;

-- The sweep's candidates: live rows only.
CREATE INDEX IF NOT EXISTS browser_sessions_live
    ON elitea_auth.browser_sessions (last_seen_at)
    WHERE ended_at IS NULL AND revoked_at IS NULL;
