-- 0168_workspace_store.sql — the Elitea workspace store (ADR-0034 decisions 2,
-- 3 and 15): refs, the segment log, and the hidden `workspace` bucket type.
--
-- workspace_refs: a thread's ref namespace (refs/elitea/base, upstream,
-- handoff/N, cloud). A publish moves refs by compare-and-set inside one short
-- transaction that holds the thread's workspace_handoffs row lock, so the
-- ownership epoch and the refs are fenced together.
--
-- workspace_segments: the segment log. One row per published git bundle,
-- content-addressed by the SHA-256 of its bytes, with the next per-thread
-- `seq` (counted on the handoff row under its lock: no global sequence, no
-- counter shared between threads). `physical_bucket` records where the
-- object was written, so the optional dedicated workspace bucket can be set or
-- changed without moving data. A segment superseded by a COMPACT keeps its row
-- as a tombstone (`superseded_at`); the sweeper deletes the object 24 hours
-- later and stamps `object_deleted_at`.
--
-- The `workspace` bucket type: one hidden logical bucket per project, under
-- the reserved name elitea-workspaces. Every user-facing bucket and artifact
-- path refuses it; it does not count against the artifact quota.
--
-- No foreign keys into tenant tables (decision 15).
--
-- Idempotent. No BEGIN/COMMIT: the ledgered runner wraps the file.

CREATE TABLE IF NOT EXISTS elitea_runtime.workspace_refs (
    project_id        integer     NOT NULL,
    conversation_uuid uuid        NOT NULL,
    name              text        NOT NULL,
    sha               text        NOT NULL,
    seq               bigint      NOT NULL,
    updated_at        timestamptz NOT NULL DEFAULT clock_timestamp(),
    PRIMARY KEY (project_id, conversation_uuid, name),
    CONSTRAINT workspace_refs_name_valid
        CHECK (name ~ '^refs/elitea/(base|upstream|cloud|handoff/[1-9][0-9]{0,8})$'),
    CONSTRAINT workspace_refs_sha_valid CHECK (sha ~ '^[0-9a-f]{40}$')
);

CREATE TABLE IF NOT EXISTS elitea_runtime.workspace_segments (
    id                bigint      GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    project_id        integer     NOT NULL,
    conversation_uuid uuid        NOT NULL,
    seq               bigint      NOT NULL,
    epoch             bigint      NOT NULL,
    kind              text        NOT NULL,
    sha256            text        NOT NULL,
    byte_length       bigint      NOT NULL,
    prerequisites     jsonb       NOT NULL DEFAULT '[]'::jsonb,
    refs              jsonb       NOT NULL DEFAULT '{}'::jsonb,
    writer            text        NOT NULL,
    object_key        text        NOT NULL,
    physical_bucket   text        NOT NULL,
    created_at        timestamptz NOT NULL DEFAULT clock_timestamp(),
    superseded_at     timestamptz,
    object_deleted_at timestamptz,
    CONSTRAINT workspace_segments_kind_valid CHECK (kind IN ('COMPACT', 'PUSH')),
    CONSTRAINT workspace_segments_sha_valid CHECK (sha256 ~ '^[0-9a-f]{64}$'),
    CONSTRAINT workspace_segments_bytes_valid CHECK (byte_length > 0),
    CONSTRAINT workspace_segments_writer_valid CHECK (writer IN ('desktop', 'cloud_executor')),
    CONSTRAINT workspace_segments_seq_valid CHECK (seq > 0)
);

-- The fetch plan and the per-thread seq: (conversation_uuid, seq), unique per
-- project.
CREATE UNIQUE INDEX IF NOT EXISTS workspace_segments_conversation_seq
    ON elitea_runtime.workspace_segments (conversation_uuid, seq, project_id);

-- The sweeper: superseded segments whose object is still stored.
CREATE INDEX IF NOT EXISTS workspace_segments_superseded
    ON elitea_runtime.workspace_segments (superseded_at)
    WHERE superseded_at IS NOT NULL AND object_deleted_at IS NULL;

-- The per-project workspace ceiling sums the live segments of a project.
CREATE INDEX IF NOT EXISTS workspace_segments_project_live
    ON elitea_runtime.workspace_segments (project_id)
    WHERE superseded_at IS NULL;

ALTER TABLE elitea_storage.buckets DROP CONSTRAINT IF EXISTS buckets_type_valid;
ALTER TABLE elitea_storage.buckets ADD CONSTRAINT buckets_type_valid
    CHECK (bucket_type IN ('system', 'autogenerated', 'local', 'workspace'));

-- At most one live workspace bucket per project.
CREATE UNIQUE INDEX IF NOT EXISTS buckets_project_workspace_uniq
    ON elitea_storage.buckets (project_id)
    WHERE bucket_type = 'workspace' AND deleted_at IS NULL;
