//! MD5 and SHA-256, for two deterministic choices — never for security.
//!
//! * MD5: the root-document proximity pass picks an anchor per top-level
//!   directory with `int.from_bytes(md5(node_id)[:8], "big")`, a stable
//!   hash (Python's `hash()` is seeded per process).
//! * SHA-256: the parity stand-in embedding (`replay::standin_embedding`).
//!
//! Both are short and fixed, so they are written here instead of adding
//! two crates for about a hundred lines. The tests hold them to the
//! published test vectors.

/// The first eight bytes of the MD5 digest of `data`, big-endian.
#[must_use]
pub fn md5_prefix_u64(data: &[u8]) -> u64 {
    let digest = md5(data);
    let mut prefix = [0u8; 8];
    prefix.copy_from_slice(&digest[..8]);
    u64::from_be_bytes(prefix)
}

/// Pad `data` as both MD5 and SHA-256 do: `0x80`, zeros to 56 mod 64, then
/// the bit length (little-endian for MD5, big-endian for SHA-256).
fn padded(data: &[u8], big_endian: bool) -> Vec<u8> {
    let bits = (data.len() as u64).wrapping_mul(8);
    let mut message = Vec::with_capacity(data.len() + 72);
    message.extend_from_slice(data);
    message.push(0x80);
    while message.len() % 64 != 56 {
        message.push(0);
    }
    if big_endian {
        message.extend_from_slice(&bits.to_be_bytes());
    } else {
        message.extend_from_slice(&bits.to_le_bytes());
    }
    message
}

