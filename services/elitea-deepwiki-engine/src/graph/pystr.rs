//! Python string semantics the builder's output depends on.
//!
//! Node ids, chunk boundaries and section names come from Python `str`
//! methods whose Unicode rules differ from Rust's: `str.strip()` also strips
//! U+001C..U+001F, `str.isprintable()` is a general-category rule, and
//! `pathlib` splits a suffix differently from `std::path`. Text files are
//! read in Python's text mode, which translates `\r\n` and `\r` to `\n`.

/// `str.isspace()`: Rust's `White_Space` plus U+001C..U+001F, which Python
/// counts as whitespace by their bidirectional class.
#[must_use]
pub fn is_space(c: char) -> bool {
    c.is_whitespace() || ('\u{1c}'..='\u{1f}').contains(&c)
}

/// `str.strip()` with no argument.
#[must_use]
pub fn strip(text: &str) -> &str {
    text.trim_matches(is_space)
}

/// `str.isprintable()` for one character: false for the general categories
/// Cc, Cf, Cs, Co, Cn, Zl, Zp and Zs, except the ASCII space.
#[must_use]
pub fn is_printable(c: char) -> bool {
    let code = u32::from(c);
    NON_PRINTABLE
        .binary_search_by(|&(low, high)| {
            if high < code {
                std::cmp::Ordering::Less
            } else if low > code {
                std::cmp::Ordering::Greater
            } else {
                std::cmp::Ordering::Equal
            }
        })
        .is_err()
}

/// The first `count` characters (`text[:count]`).
#[must_use]
pub fn prefix_chars(text: &str, count: usize) -> &str {
    match text.char_indices().nth(count) {
        Some((end, _)) => &text[..end],
        None => text,
    }
}

/// The last path component (`PurePath.name`).
#[must_use]
pub fn file_name(path: &str) -> &str {
    let trimmed = path.trim_end_matches('/');
    trimmed.rsplit('/').next().unwrap_or(trimmed)
}

/// `PurePath.suffix` (Python 3.12): the text from the last dot, unless the
/// dot is first or last in the name. `std::path` differs on `"foo."`.
#[must_use]
pub fn suffix(path: &str) -> &str {
    let name = file_name(path);
    match name.rfind('.') {
        Some(dot) if dot > 0 && dot < name.len() - 1 => &name[dot..],
        _ => "",
    }
}

/// `PurePath.stem` (Python 3.12).
#[must_use]
pub fn stem(path: &str) -> &str {
    let name = file_name(path);
    match name.rfind('.') {
        Some(dot) if dot > 0 && dot < name.len() - 1 => &name[..dot],
        _ => name,
    }
}

/// How undecodable bytes are handled (`errors=`).
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Errors {
    /// Drop each maximal invalid subsequence.
    Ignore,
    /// Replace each maximal invalid subsequence with U+FFFD.
    Replace,
}

/// `open(path, encoding="utf-8", errors=...).read()`: decode, then apply
/// universal newlines.
#[must_use]
pub fn decode_text(bytes: &[u8], errors: Errors) -> String {
    let mut decoded = String::with_capacity(bytes.len());
    for chunk in bytes.utf8_chunks() {
        decoded.push_str(chunk.valid());
        if !chunk.invalid().is_empty() && errors == Errors::Replace {
            decoded.push('\u{fffd}');
        }
    }
    if decoded.contains('\r') {
        decoded = decoded.replace("\r\n", "\n").replace('\r', "\n");
    }
    decoded
}

/// `str.splitlines()` (no `keepends`): the line boundaries are `\n`,
/// `\r`, `\r\n`, U+000B, U+000C, U+001C..U+001E, U+0085, U+2028 and
/// U+2029; a trailing boundary does not open an empty last line.
#[must_use]
pub fn splitlines(text: &str) -> Vec<&str> {
    splitline_spans(text)
        .into_iter()
        .map(|(start, end)| &text[start..end])
        .collect()
}

/// The byte spans of [`splitlines`].
#[must_use]
pub fn splitline_spans(text: &str) -> Vec<(usize, usize)> {
    let mut spans = Vec::new();
    let mut start = 0;
    let mut chars = text.char_indices().peekable();
    while let Some((at, c)) = chars.next() {
        let boundary = matches!(
            c,
            '\n' | '\r'
                | '\u{b}'
                | '\u{c}'
                | '\u{1c}'
                | '\u{1d}'
                | '\u{1e}'
                | '\u{85}'
                | '\u{2028}'
                | '\u{2029}'
        );
        if !boundary {
            continue;
        }
        spans.push((start, at));
        let mut end = at + c.len_utf8();
        if c == '\r' && chars.peek().is_some_and(|&(_, next)| next == '\n') {
            chars.next();
            end += 1;
        }
        start = end;
    }
    if start < text.len() {
        spans.push((start, text.len()));
    }
    spans
}

/// `str.split()` with no argument: runs of whitespace separate, and no
/// empty part is kept.
pub fn split_whitespace(text: &str) -> impl Iterator<Item = &str> {
    text.split(is_space).filter(|part| !part.is_empty())
}

/// `str.strip(chars)`.
#[must_use]
pub fn strip_chars<'t>(text: &'t str, chars: &str) -> &'t str {
    text.trim_matches(|c| chars.contains(c))
}

/// `s[0].upper() + s[1:]` (empty stays empty).
#[must_use]
pub fn upper_first(text: &str) -> String {
    let mut chars = text.chars();
    chars.next().map_or_else(String::new, |first| {
        first.to_uppercase().chain(chars).collect()
    })
}

/// `str.capitalize()`: the first character upper-cased, the rest
/// lower-cased. (Python title-cases the first character; the two differ
/// only for the four Latin digraph letters.)
#[must_use]
pub fn capitalize(text: &str) -> String {
    let mut chars = text.chars();
    chars.next().map_or_else(String::new, |first| {
        first
            .to_uppercase()
            .chain(chars.as_str().to_lowercase().chars())
            .collect()
    })
}

/// `posixpath.basename`.
#[must_use]
pub fn basename(path: &str) -> &str {
    path.rfind('/').map_or(path, |slash| &path[slash + 1..])
}

/// `posixpath.dirname`: the head before the last `/`, trailing slashes
/// removed unless the head is all slashes.
#[must_use]
pub fn dirname(path: &str) -> &str {
    let head = path.rfind('/').map_or("", |slash| &path[..=slash]);
    if !head.is_empty() && head.chars().any(|c| c != '/') {
        head.trim_end_matches('/')
    } else {
        head
    }
}

/// `posixpath.join(a, b)` for two parts.
#[must_use]
pub fn join(a: &str, b: &str) -> String {
    if b.starts_with('/') {
        b.to_owned()
    } else if a.is_empty() || a.ends_with('/') {
        format!("{a}{b}")
    } else {
        format!("{a}/{b}")
    }
}

/// `posixpath.normpath`: `.` and empty parts dropped, `..` folded, two
/// leading slashes kept (POSIX leaves `//` implementation-defined), three
/// or more collapsed to one; an empty result is `.`.
#[must_use]
pub fn normpath(path: &str) -> String {
    if path.is_empty() {
        return ".".to_owned();
    }
    let initial_slashes = if path.starts_with("//") && !path.starts_with("///") {
        2
    } else {
        usize::from(path.starts_with('/'))
    };
    let mut parts: Vec<&str> = Vec::new();
    for part in path.split('/') {
        if part.is_empty() || part == "." {
            continue;
        }
        if part != ".." || (initial_slashes == 0 && parts.is_empty()) || parts.last() == Some(&"..")
        {
            parts.push(part);
        } else if !parts.is_empty() {
            parts.pop();
        }
    }
    let joined = format!("{}{}", "/".repeat(initial_slashes), parts.join("/"));
    if joined.is_empty() {
        ".".to_owned()
    } else {
        joined
    }
}

/// `fnmatch.fnmatchcase(name, pattern)`: `*` matches any run of characters
/// INCLUDING `/`, `?` one character, `[seq]` / `[!seq]` a set. A `[`
/// without a closing `]` is literal, as in `fnmatch.translate`.
#[must_use]
pub fn fnmatch(name: &str, pattern: &str) -> bool {
    let name: Vec<char> = name.chars().collect();
    let pattern: Vec<char> = pattern.chars().collect();
    fnmatch_at(&name, &pattern)
}

fn fnmatch_at(name: &[char], pattern: &[char]) -> bool {
    // Iterative glob matching with one backtrack point per `*`.
    let (mut n, mut p) = (0, 0);
    let mut star: Option<(usize, usize)> = None;
    while n < name.len() {
        if p < pattern.len() {
            match pattern[p] {
                '*' => {
                    star = Some((p, n));
                    p += 1;
                    continue;
                }
                '?' => {
                    n += 1;
                    p += 1;
                    continue;
                }
                '[' => {
                    if let Some((matched, next)) = match_set(&pattern[p..], name[n]) {
                        if matched {
                            n += 1;
                            p += next;
                            continue;
                        }
                    } else if name[n] == '[' {
                        n += 1;
                        p += 1;
                        continue;
                    }
                }
                literal if literal == name[n] => {
                    n += 1;
                    p += 1;
                    continue;
                }
                _ => {}
            }
        }
        match star {
            Some((star_p, star_n)) => {
                p = star_p + 1;
                n = star_n + 1;
                star = Some((star_p, star_n + 1));
            }
            None => return false,
        }
    }
    pattern[p..].iter().all(|&c| c == '*')
}

/// Match `c` against the set starting at `pattern[0] == '['`. Returns
/// whether it matched and the set's length, or `None` when the set is not
/// closed (then `[` is a literal).
fn match_set(pattern: &[char], c: char) -> Option<(bool, usize)> {
    let mut i = 1;
    let negated = matches!(pattern.get(i), Some('!'));
    if negated {
        i += 1;
    }
    // A `]` right after `[` or `[!` is a member.
    if pattern.get(i) == Some(&']') {
        i += 1;
    }
    while pattern.get(i).is_some_and(|&ch| ch != ']') {
        i += 1;
    }
    if i >= pattern.len() {
        return None;
    }
    let body_start = if negated { 2 } else { 1 };
    let body = &pattern[body_start..i];
    let mut matched = false;
    let mut j = 0;
    while j < body.len() {
        if j + 2 < body.len() && body[j + 1] == '-' {
            if body[j] <= c && c <= body[j + 2] {
                matched = true;
            }
            j += 3;
        } else {
            if body[j] == c {
                matched = true;
            }
            j += 1;
        }
    }
    Some((matched != negated, i + 1))
}

