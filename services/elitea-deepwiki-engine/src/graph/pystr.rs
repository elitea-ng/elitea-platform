#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn strip_and_space_follow_python() {
        assert_eq!(strip("\u{1c} a \u{a0}\t"), "a");
        assert!(is_space('\u{1f}'));
        assert!(!is_space('\u{200b}'));
    }

    #[test]
    fn printable_follows_python() {
        assert!(is_printable(' '));
        assert!(is_printable('é'));
        assert!(is_printable('😀'));
        for c in [
            '\t', '\u{a0}', '\u{200b}', '\u{200d}', '\u{feff}', '\u{e000}', '\u{378}',
        ] {
            assert!(!is_printable(c), "{c:?}");
        }
    }

    #[test]
    fn suffix_and_stem_follow_pathlib() {
        assert_eq!((suffix("a/foo."), stem("a/foo.")), ("", "foo."));
        assert_eq!((suffix(".env"), stem(".env")), ("", ".env"));
        assert_eq!((suffix("x/a.tar.gz"), stem("x/a.tar.gz")), (".gz", "a.tar"));
        assert_eq!((suffix("x..y"), stem("x..y")), (".y", "x."));
        assert_eq!((suffix(".a.b"), stem(".a.b")), (".b", ".a"));
    }

    #[test]
    fn decoding_uses_universal_newlines() {
        assert_eq!(decode_text(b"a\r\nb\rc\n", Errors::Ignore), "a\nb\nc\n");
        assert_eq!(decode_text(b"a\xffb", Errors::Ignore), "ab");
        assert_eq!(decode_text(b"a\xffb", Errors::Replace), "a\u{fffd}b");
    }

    #[test]
    fn fnmatch_star_crosses_slashes() {
        assert!(fnmatch("/a/node_modules/b/c.js", "**/node_modules/**"));
        assert!(fnmatch("/node_modules/x", "**/node_modules/**"));
        assert!(!fnmatch("node_modules/x", "**/node_modules/**"));
        assert!(fnmatch("/x/Foo.class", "**/*.class"));
        assert!(!fnmatch("/x/Foo.classy", "**/*.class"));
        assert!(fnmatch("/a/b", "/a/?"));
        assert!(fnmatch("/a/c", "/a/[a-c]"));
        assert!(!fnmatch("/a/c", "/a/[!a-c]"));
        assert!(fnmatch("/a/[", "/a/["));
    }

    #[test]
    fn prefix_counts_characters() {
        assert_eq!(prefix_chars("héllo", 2), "hé");
        assert_eq!(prefix_chars("hé", 5), "hé");
    }

    #[test]
    fn splitlines_follows_python() {
        assert_eq!(
            splitlines("a\nb\r\nc\rd\u{b}e\u{2028}f\n"),
            ["a", "b", "c", "d", "e", "f"]
        );
        assert_eq!(splitlines("\n\nx"), ["", "", "x"]);
        assert!(splitlines("").is_empty());
        assert_eq!(splitlines("\u{1f}x"), ["\u{1f}x"]);
    }

    #[test]
    fn posix_paths_follow_python() {
        assert_eq!(normpath("docs/../src/a.go"), "src/a.go");
        assert_eq!(normpath("../a"), "../a");
        assert_eq!(normpath("/../a"), "/a");
        assert_eq!(normpath("//a//b/"), "//a/b");
        assert_eq!(normpath("///a"), "/a");
        assert_eq!(normpath("a/.."), ".");
        assert_eq!(normpath("a/../../b"), "../b");
        assert_eq!(dirname("a/b/c.md"), "a/b");
        assert_eq!(dirname("c.md"), "");
        assert_eq!(dirname("/c.md"), "/");
        assert_eq!(dirname("a//c.md"), "a");
        assert_eq!(basename("a/b/c.md"), "c.md");
        assert_eq!(join("", "x"), "x");
        assert_eq!(join("a", "/x"), "/x");
        assert_eq!(join("a", "x"), "a/x");
    }

    #[test]
    fn case_helpers_follow_python() {
        assert_eq!(capitalize("gET_x"), "Get_x");
        assert_eq!(upper_first("listItems"), "ListItems");
        assert_eq!(upper_first(""), "");
        assert_eq!(strip_chars("'\"/x\"'", "\"'"), "/x");
        assert_eq!(
            split_whitespace(" a\u{1c}b  c ").collect::<Vec<_>>(),
            ["a", "b", "c"]
        );
    }
}
